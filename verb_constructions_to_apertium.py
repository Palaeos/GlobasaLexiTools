# Governed prepositions (verb_constructions.tsv) -> lexical selection in the X->glb pairs.
# Output only: the source of truth is verb_constructions.tsv (verb_constructions.py builds the
# proposals from the Wiktionary senses); nothing is read back from the pairs.
#
#   python3 verb_constructions_to_apertium.py
#   (cd GlobasaTranslation/apertium-glb-deu && make)   # likewise nld, fra, spa
#
# For each row with sense_status=ok (stage 1, the Wiktionary sense) and status=ok (stage 2, a
# fluent speaker's decision) and a governed preposition (kind obj or prep, not reflexive):
#   lrx   verb [0-2 words] prep  ->  the row's Globasa preposition, or el when the Globasa verb
#         takes the object directly (kind obj; the shared step glb-story.py drops el, Xwexi 03
#         "typically omitted"); the verb itself is selected as the row's Globasa verb.
#   dix   r="RL" entries the pair lacks: the verb (glb <- source) and the preposition's Globasa
#         reading (el/tem/... <- prep), so lrx has something to select.
# Reflexive rows (se, soho, cu, xor, state, lexical) are counted, not generated: they need the
# reflexive pronoun handled in the transfer (pending, see verb_constructions.py).
#
# Writes, per pair, blocks BEGIN/END verb-constructions:
#   apertium-glb-X.glb-X.dix     above the build_bidix marker
#   apertium-glb-X.X-glb.lrx     before </rules>
import html
import re
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).parent
PAIRS = {"de": "deu", "nl": "nld", "fr": "fra", "es": "spa"}
LIST = HERE / "verb_constructions.tsv"
MARK = "<!-- Autogenerated common words -->"
BEGIN = ("<!-- BEGIN verb-constructions: generated from verb_constructions.tsv by "
         "verb_constructions_to_apertium.py; do not edit -->")
END = "<!-- END verb-constructions -->"


def esc(s):
    return html.escape(s, quote=True)


def sides(text):
    """Dix text with spaces as <b/> (multiword lemmas)."""
    return esc(text).replace(" ", "<b/>")


def strip_block(text):
    return re.sub(r"[ \t]*" + re.escape("<!-- BEGIN verb-constructions") + r".*?" + re.escape(END) + r"\n?",
                  "", text, flags=re.S)


def has_rl(dix, glb, sym, src):
    """Does the dix already translate src<sym> to glb (any entry, any direction but LR)?"""
    pat = (r"<e(?![^>]*r=\"LR\")[^>]*>\s*<p>\s*<l>" + re.escape(sides(glb)) + r'<s n ?= ?"' + sym
           + r'"/>.*?</l>\s*<r>' + re.escape(sides(src)) + r'<s n ?= ?"' + sym + '"')
    return re.search(pat, dix) is not None


rows = []
with open(LIST, encoding="utf-8") as f:
    header = f.readline().rstrip("\n").split("\t")
    rows = [dict(zip(header, line.rstrip("\n").split("\t"))) for line in f if line.strip()]

ok = [r for r in rows if r.get("sense_status") == "ok" and r.get("status") == "ok"]
skipped = Counter()
by_pair = defaultdict(list)
for r in ok:
    if r["lang"] not in PAIRS:
        skipped["language without a pair"] += 1
    elif r["reflexive"] == "1":
        skipped["reflexive (transfer support pending)"] += 1
    elif not r["prep"] or r["kind"] not in ("obj", "prep") or not r["glb"]:
        skipped["no governed preposition / no Globasa verb"] += 1
    else:
        by_pair[PAIRS[r["lang"]]].append(r)

for code, prs in sorted(by_pair.items()):
    pair = HERE / "GlobasaTranslation" / f"apertium-glb-{code}"
    dix_path = pair / f"apertium-glb-{code}.glb-{code}.dix"
    lrx_path = pair / f"apertium-glb-{code}.{code}-glb.lrx"
    dix = strip_block(dix_path.read_text(encoding="utf-8"))
    lrx = strip_block(lrx_path.read_text(encoding="utf-8"))
    entries, rules, done = [], [], set()
    for r in prs:
        verb, prep, glb = r["verb"], r["prep"], r["glb"]
        target = r["glb_prep"] if r["kind"] == "prep" and r["glb_prep"] else "el"
        for g, sym, s in ((glb, "vblex", verb), (target, "pr", prep)):
            if (g, sym, s) not in done and not has_rl(dix, g, sym, s):
                entries.append(f'<e r="RL"><p><l>{sides(g)}<s n="{sym}"/></l>'
                               f'<r>{sides(s)}<s n="{sym}"/></r></p></e>')
            done.add((g, sym, s))
        note = esc(f"{verb} + {prep}: {r['gloss'][:60]}")
        for gap in range(3):
            rules.append(
                f'  <rule weight="3.0"><!-- {note} -->'
                f'<match lemma="{esc(verb)}" tags="vblex.*"><select lemma="{esc(glb)}"/></match>'
                + "<match/>" * gap
                + f'<match lemma="{esc(prep)}" tags="pr.*"><select lemma="{esc(target)}"/></match></rule>')
    i = dix.index(MARK)
    dix = dix[:i] + BEGIN + "\n" + "\n".join(entries) + ("\n" if entries else "") + END + "\n" + dix[i:]
    j = lrx.rindex("</rules>")
    lrx = lrx[:j] + "  " + BEGIN + "\n" + "\n".join(rules) + "\n  " + END + "\n" + lrx[j:]
    dix_path.write_text(dix, encoding="utf-8")
    lrx_path.write_text(lrx, encoding="utf-8")
    print(f"apertium-glb-{code}: {len(prs)} constructions, {len(entries)} dix entries, {len(rules)} lrx rules")

print(f"{len(ok)} rows vetted ok in both stages; skipped: {dict(skipped) or 'none'}")
