"""Globasa third-person pronoun class per word, for the eng->glb coreference step.

Sources (curated, the source of truth; this script only reads them):
  menalariPronouns_edited.tsv   Word -> Pronoun (te, to, "to, te", mante, femte)
  menalariAnaphorSenses.tsv     per-sense te/to for plant and food words; a word listed here
                                takes the union of its senses' pronouns (a pronoun belongs to a
                                sense, so flura = te (live plant) + to (cut flower))

Writes glb-anaphor.tsv (Word<TAB>te | to | te,to) into every pair with a coreference step:
apertium-glb-eng (eng-glb-neural.py), apertium-glb-fra (fra-glb-neural.py) and the pairs using
the shared glb-neural.py (spa, deu, nld).
mante/femte count as te (animate). Words with no recorded pronoun are left out; the step then
falls back to WordNet and says so in its trace.
"""
import csv
from collections import defaultdict

OUTS = [f"GlobasaTranslation/apertium-glb-{lang}/glb-anaphor.tsv"
        for lang in ("eng", "fra", "spa", "deu", "nld", "jpn")]
CLASS = {"te": "te", "to": "to", "mante": "te", "femte": "te"}

classes = defaultdict(set)
with open("menalariPronouns_edited.tsv", encoding="utf-8") as f:
    for row in csv.DictReader(f, delimiter="\t"):
        word = row["Word"].strip()
        for p in row["Pronoun"].split(","):
            if p.strip() in CLASS:
                classes[word].add(CLASS[p.strip()])

senses = defaultdict(set)
with open("menalariAnaphorSenses.tsv", encoding="utf-8") as f:
    for row in csv.DictReader(f, delimiter="\t"):
        if row["Anaphor"].strip() in CLASS:
            senses[row["Word"].strip()].add(CLASS[row["Anaphor"].strip()])
classes.update(senses)                  # sense-level data overrides the word-level pronoun

text = "".join(["# generated by anaphor_to_apertium.py from menalariPronouns_edited.tsv"
                " + menalariAnaphorSenses.tsv; do not edit\n"]
               + [f"{word}\t{','.join(sorted(classes[word]))}\n"
                  for word in sorted(classes) if classes[word]])
for out in OUTS:
    with open(out, "w", encoding="utf-8") as f:
        f.write(text)

counts = defaultdict(int)
for c in classes.values():
    counts[",".join(sorted(c))] += 1
print(f"{', '.join(OUTS)}: {sum(counts.values())} words", dict(counts))
