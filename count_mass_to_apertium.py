# Counted vs uncounted English nouns -> lexical selection in the eng->glb pair
# (GlobasaTranslation/apertium-glb-eng). Output only: the source of truth is count_mass_nouns.tsv;
# nothing is read back from the pair.
#
#   python3 count_mass_to_apertium.py
#   (cd GlobasaTranslation/apertium-glb-eng && make)
#
# Globasa nouns have no number and no articles (Xwexi 02.inharelexi), so an English noun used
# uncounted (bare singular: "for man", "long hair") and the same noun counted ("a man", "two men",
# "a hair") are told apart by word choice: man -> insan / manixu, hair -> tofa / tofamon.
# The English analyser has no countability tags, so the cue is the noun's own number and the
# determiner before it (up to two adjectives in between):
#   counted    plural noun; a/an/another/each/every (det.ind.sg), several (det.ind.pl),
#              many/few/all (det.qnt.pl), these/those (det.dem.pl), numerals (num)
#   uncounted  bare singular (the default rule); much/little (det.qnt.sg), some (det.qnt.sp)
#   weak       the (det.def), this/that (det.dem.sg), possessives (det.pos), any/no (det.ind.sp):
#              the row's `weak` column says which side they take (man: counted; hair: uncounted)
# Rows with status=add only; pending rows are documented, not generated. A row whose counted and
# uncounted words are the same is just a bidix entry.
#
# Writes:
#   apertium-glb-eng.glb-eng.dix   block BEGIN/END count-mass above the build_bidix marker, r="RL"
#   apertium-glb-eng.eng-glb.lrx   block BEGIN/END count-mass before </rules>
import csv
import html
import re
import sys
from pathlib import Path

HERE = Path(__file__).parent
PAIR = HERE / "GlobasaTranslation" / "apertium-glb-eng"
DIX = PAIR / "apertium-glb-eng.glb-eng.dix"
LRX = PAIR / "apertium-glb-eng.eng-glb.lrx"
LIST = HERE / "count_mass_nouns.tsv"
MARK = "<!-- Autogenerated common words -->"
BEGIN = "<!-- BEGIN count-mass: generated from count_mass_nouns.tsv by count_mass_to_apertium.py; do not edit -->"
END = "<!-- END count-mass -->"

COUNTED = ["det.ind.sg", "det.ind.pl", "det.qnt.pl", "det.dem.pl", "num.*"]
UNCOUNTED = ["det.qnt.sg", "det.qnt.sp"]
WEAK = ["det.def.*", "det.dem.sg", "det.pos.*", "det.ind.sp"]


def tags(t):
    return "".join(f'<s n="{x}"/>' for x in t.split(".") if x)


def rule(weight, cues, lemma, select, comment):
    # cue, then 0-2 adjectives, then the noun
    out = []
    for n_adj in range(3):
        ctx = "".join(f'<match tags="{c}"/>' for c in cues[:1]) if cues else ""
        alts = "".join(f'<match tags="{c}"/>' for c in cues)
        ctx = f"<or>{alts}</or>" if len(cues) > 1 else ctx
        adj = '<match tags="adj.*"/>' * n_adj
        out.append(f'  <rule weight="{weight}"><!-- {comment} -->{ctx}{adj}'
                   f'<match lemma="{lemma}" tags="n.*"><select lemma="{select}" tags="n.*"/></match></rule>')
    return out


dix = DIX.read_text(encoding="utf-8")
dix = re.sub(re.escape("<!-- BEGIN count-mass") + r".*?" + re.escape(END) + r"\n?", "", dix, flags=re.S)

rows = [r for r in csv.DictReader(LIST.open(encoding="utf-8"), delimiter="\t") if r["status"] == "add"]
entries, rules = [], []
for r in rows:
    e = r["eng"]
    pairs = {(r["counted"], r["counted_tags"]), (r["uncounted"], r["uncounted_tags"])}
    for g, t in sorted(pairs):
        # the selection needs both translations in the bidix; add only the missing ones
        if re.search(rf"<l>{re.escape(g)}<s n=\"n\"/>.*?<r>{re.escape(e)}<s n=\"n\"/>", dix):
            continue
        entries.append(f'<e r="RL"><p><l>{html.escape(g)}{tags(t)}</l>   <r>{html.escape(e)}<s n="n"/></r></p></e>')
    if r["counted"] == r["uncounted"]:
        continue
    weak = r["counted"] if r["weak"] == "counted" else r["uncounted"]
    rules.append(f'  <!-- {e}: counted {r["counted"]}, uncounted {r["uncounted"]}; weak cues -> {weak} -->')
    rules.append(f'  <rule weight="0.5"><!-- bare singular: uncounted --><match lemma="{e}" tags="n.sg"><select lemma="{r["uncounted"]}" tags="n.*"/></match></rule>')
    rules.append(f'  <rule weight="1.0"><!-- plural: counted --><match lemma="{e}" tags="n.pl"><select lemma="{r["counted"]}" tags="n.*"/></match></rule>')
    rules += rule("1.0", COUNTED, e, r["counted"], "count cue")
    rules += rule("1.0", UNCOUNTED, e, r["uncounted"], "mass cue")
    rules += rule("1.0", WEAK, e, weak, "weak cue")

i = dix.find(MARK)
if i < 0:
    sys.exit(f"no '{MARK}' in {DIX}")
DIX.write_text(dix[:i] + BEGIN + "\n" + "\n".join(entries) + "\n" + END + "\n" + dix[i:], encoding="utf-8")

lrx = LRX.read_text(encoding="utf-8")
lrx = re.sub(r"[ \t]*" + re.escape("<!-- BEGIN count-mass") + r".*?" + re.escape(END) + r"\n?", "", lrx, flags=re.S)
j = lrx.rfind("</rules>")
LRX.write_text(lrx[:j] + "  " + BEGIN + "\n" + "\n".join(rules) + "\n  " + END + "\n" + lrx[j:], encoding="utf-8")
print(f"{len(rows)} rows: {len(entries)} bidix entries, {sum(1 for x in rules if '<rule' in x)} lrx rules")
