"""Build the generated part of the glb-X Apertium bilingual dictionaries.

Each apertium-glb-X/apertium-glb-X.glb-X.dix has two parts:
  - a curated part, written by hand: symbol definitions, paradigms, the
    function words and hand fixes. This script never touches it.
  - a generated part, everything below '<!-- Autogenerated common words -->',
    which this script rebuilds from the word list and the Wiktionary extension.

The generated part only adds. It never emits function words, and it never
claims a direction the curated part already covers: a (Globasa lemma, PoS)
written by hand blocks generated glb→X entries for it, a (target lemma, PoS)
written by hand blocks generated X→glb entries for it.

Directions:
  - word-list glosses: both ways (glb→X yields the word-list gloss);
  - Wiktionary-only translations (menalariExtension.tsv): X→glb only
    (r="RL"), so Wiktionary synonyms are understood but never produced.

Every target lemma is checked with the target analyser ({lang}.automorf.bin);
lemmas it cannot analyse as that lemma and PoS are dropped and reported.

Run:    python3 build_bidix.py [lang ...]   (default: every pair)

Reads:  word-list.csv, menalariExtension.tsv (Wiktionary extension builder.py),
        menalariPronouns_edited.tsv, the pair dixes and target analysers
Writes: dictionary_{lang}_bidix.xml   generated entries, one file per pair
        bidix_entries.tsv            every entry written, with its origin
        bidix_report.tsv             every candidate dropped, with the reason
        and merges each xml into its pair dix below the marker (.bak kept)
"""

import csv
import os
import re
import subprocess
import sys
from collections import Counter, defaultdict
from xml.sax.saxutils import unescape as xml_unescape

import pandas as pd

from Lexilista_parser import parseWordEntry
from apertium_common import (
    FUNCTION_POS, NOUN_SYMBOLS, apertium_symbol, expand_gloss_tokens,
    genderDict, split_foreign_gender, bilingual_entry,
    APERTIUM_MARKER, APERTIUM_ROOT, merge_into_dix,
)
from wiktionary_constants import pos_groups

# ── Configuration ───────────────────────────────────────────────────────

FALLBACK_ROOT = "/usr/local/old-apertium-2024/share/apertium"

# (Apertium code, label for bilingual_entry, word-list parser code,
#  word-list column, menalariExtension.tsv column)
PAIRS = [
    ("eng", "En", "Eng", "TranslationEng", None),
    ("deu", "De", "Deu", "TranslationDeu", "German"),
    ("fra", "Fr", "Fra", "TranslationFra", "French"),
    ("nld", "Nl", None,  None,             "Dutch"),
    ("jpn", "Ja", None,  None,             "Japanese"),
]

# Optional: build only the pairs named on the command line (build_bidix.py jpn).
if sys.argv[1:]:
    PAIRS = [p for p in PAIRS if p[0] in sys.argv[1:]]

# Globasa-side symbol: apertium-glb files proper nouns under the common-noun
# paradigms (apertium-glb ed4f24f), so its analyser and generator say
# Maria<n><ut>, never <np>.
GLB_SYMBOLS = {"np": "n"}

# Target-side PoS symbol where the target analyser differs from Globasa's.
TARGET_SYMBOLS = {
    "jpn": {"vblex": "v", "np": "pn"},
}

# Targets whose gender-like analyser tags are not grammatical gender
# (apertium-jpn tags 父<n><m> for meaning only): no gender on <r>.
NO_TARGET_GENDER = {"jpn"}

# Targets that file language, religion and scripture names as common nouns (英語, 仏教, 聖書):
# a Globasa proper noun may take a target <n> when the analyser has no proper-noun reading.
PROPER_AS_COMMON = {"jpn"}

# Targets whose analyser splits compounds into joined parts (加入者 → 加入+者<suff>): the entry
# keeps the whole compound, which apertium-glb-jpn's compounds.py re-joins at run time.
REJOINED_COMPOUNDS = {"jpn"}

# Attributive endings a Wiktionary translation may carry that the analyser
# files under the bare lemma (偉大な → 偉大<adj><adj_na>, 青の → 青).
ATTRIBUTIVE_ENDINGS = {"jpn": ("な", "の")}

# Pairs whose dix gets the merge (every pair's xml and TSV rows are still
# written). BIDIX_MERGE=fra merges into glb-fra only; unset = all pairs.
MERGE_LANGS = set(filter(None, os.environ.get("BIDIX_MERGE", "").split(","))) \
    or {lang for lang, *_ in PAIRS}

# Per-language cleanup of a Wiktionary translation before lookup, e.g. for
# Russian stress marks or Latin macrons once those pairs exist.
NORMALISE = {}

# Generated entries never cover these: they belong to the curated part.
FUNCTION_SYMBOLS = {"pr", "det", "prn", "num", "cnjsub", "cnjcoo", "cnjadv",
                    "vbmod", "vbser"}

# Target-side gender tags as the analysers write them.
TARGET_GENDERS = {"m", "f", "nt", "mf", "ut", "mfn"}
# Analyser readings that are only compound parts or case variants.
SKIP_READING_TAGS = {"cmp", "compound-only-L", "compound-R", "lower"}

EXTENSION_TSV = "menalariExtension.tsv"
ENTRIES_TSV = "bidix_entries.tsv"
REPORT_TSV = "bidix_report.tsv"


def pair_dix_path(root, lang):
    return os.path.join(root, f"apertium-glb-{lang}", f"apertium-glb-{lang}.glb-{lang}.dix")


def analyser_path(root, lang):
    return os.path.join(root, f"apertium-{lang}", f"{lang}.automorf.bin")


# ── Inputs ──────────────────────────────────────────────────────────────

wordlist = pd.read_csv("word-list.csv", index_col=0, keep_default_na=False)
wordlist.index = wordlist.index.astype(str).str.strip()

pronouns = pd.read_csv("menalariPronouns_edited.tsv", sep="\t",
                       index_col=0, keep_default_na=False)
pronouns = pronouns[~pronouns.index.duplicated(keep="first")]

if not os.path.exists(EXTENSION_TSV):
    sys.exit(f"No {EXTENSION_TSV}: run 'Wiktionary extension builder.py' first.")
extension = pd.read_csv(EXTENSION_TSV, sep="\t", index_col=0,
                        keep_default_na=False, quoting=csv.QUOTE_NONE)
extension = extension[~extension.index.duplicated(keep="first")]
for _, _, _, _, ext_col in PAIRS:
    if ext_col and ext_col not in extension.columns:
        sys.exit(f"{EXTENSION_TSV} has no '{ext_col}' column")


def globasa_genders(word):
    """Globasa noun genders from menalariPronouns_edited.tsv, the same source
    dictionaryPreprocess.py builds the monodix from."""
    if word in pronouns.index:
        p = pronouns.at[word, "Pronoun"]
        if isinstance(p, str) and p:
            gs = [genderDict[a] for a in p.split(", ") if a in genderDict]
            if gs:
                return gs
    return ["GD"]


# ── Stage A: candidates from the word list and the extension ────────────
# candidates[lang]: ordered {(glb, sym, target): candidate dict}
candidates = {lang: {} for lang, *_ in PAIRS}
report = []   # dropped candidates


def drop(lang, glb, sym, target, origin, reason):
    report.append({"lang": lang, "glb": glb, "glb_pos": sym or "",
                   "target": target, "origin": origin, "reason": reason})


def add_candidate(lang, glb, sym, target, origin, wikt_genders=()):
    key = (glb, sym, target)
    known = candidates[lang].get(key)
    if known:
        # A Wiktionary duplicate of a word-list gloss still tells the gender.
        for g in wikt_genders:
            if g not in known["wikt_genders"]:
                known["wikt_genders"].append(g)
        return
    candidates[lang][key] = {"glb": glb, "sym": sym, "target": target,
                             "origin": origin, "wikt_genders": list(wikt_genders)}


_ITEM_SPLIT_RE = re.compile(r",\s*(?![^()]*\))")
_ITALIC_RE = re.compile(r"\s*\(_.*?_\)")

for glb, row in wordlist.iterrows():
    if not glb or glb.startswith("-") or glb.endswith("-"):
        continue
    eng_text = str(row.get("TranslationEng", ""))
    wordclass = str(row.get("WordClass", ""))
    if not eng_text.strip():
        continue

    non_eng = {}
    for _, _, code, col, _ in PAIRS:
        if code and code != "Eng" and col in wordlist.columns:
            v = str(row.get(col, ""))
            if v and v != "False":
                non_eng[code] = v
    parsed = parseWordEntry(eng_text, wordclass, non_eng).translations
    eng_glosses = parsed.get("Eng", [])
    if not eng_glosses:
        continue
    function_head = eng_glosses[0].pos in FUNCTION_POS

    # Word-list glosses: one slot per (symbol, verb type) of the English side.
    for lang, _, code, _, _ in PAIRS:
        if not code:
            continue
        for pg in parsed.get(code, []):
            sym = apertium_symbol(pg)
            if sym is None:
                continue
            for tok in expand_gloss_tokens(pg.gloss):
                tok, _ = split_foreign_gender(tok)
                if not tok:
                    continue
                if function_head or sym in FUNCTION_SYMBOLS:
                    drop(lang, glb, sym, tok, "wordlist", "function word: curated only")
                else:
                    add_candidate(lang, glb, sym, tok, "wordlist")

    # Wiktionary extension: one '; '-separated part per pos_groups() group.
    if glb not in extension.index:
        continue
    groups = pos_groups(eng_text, wordclass)
    for lang, _, _, _, ext_col in PAIRS:
        if not ext_col:
            continue
        cell = extension.at[glb, ext_col]
        if not isinstance(cell, str) or not cell.strip():
            continue
        for i, part in enumerate(cell.split("; ")):
            if not part.strip():
                continue
            sym = apertium_symbol(groups[i][2]) if i < len(groups) else None
            for item in _ITEM_SPLIT_RE.split(part):
                item = _ITALIC_RE.sub("", item).strip()
                target, genders = split_foreign_gender(item)
                target = NORMALISE.get(lang, lambda t: t)(target.strip())
                if not target:
                    continue
                if sym is None:
                    drop(lang, glb, None, target, "wiktionary",
                         f"extension group {i + 1} has no PoS group in the word list")
                elif function_head or sym in FUNCTION_SYMBOLS:
                    drop(lang, glb, sym, target, "wiktionary", "function word: curated only")
                else:
                    add_candidate(lang, glb, sym, target, "wiktionary", genders)


# ── Stage A2: the curated part of each pair dix ─────────────────────────
_ENTRY_RE = re.compile(r"<e\b([^>]*)>(.*?)</e>", re.DOTALL)
_SIDE_RE = re.compile(r"<l>(.*?)</l>\s*<r>(.*?)</r>", re.DOTALL)
_SYM_RE = re.compile(r'<s\s+n\s*=\s*"([^"]+)"\s*/>')
_RESTRICTION_RE = re.compile(r'\br\s*=\s*"(LR|RL)"')


def side_key(side_xml):
    """'kitabu<s n="n"/><s n="nt"/>' → ('kitabu', 'n'); None for tag-only sides."""
    text = side_xml.split("<s", 1)[0]
    lemma = xml_unescape(text.replace("<b/>", " ").replace("<g>", "").replace("</g>", "")).strip()
    syms = _SYM_RE.findall(side_xml)
    if not lemma or not syms:
        return None
    return lemma, syms[0]


def curated_keys(dix_text):
    """(glb keys that have a glb→X entry, target keys that have an X→glb entry)
    in the text above the marker."""
    glb_keys, target_keys = set(), set()
    for attrs, body in _ENTRY_RE.findall(dix_text):
        m = _SIDE_RE.search(body)
        if not m:
            continue
        restriction = _RESTRICTION_RE.search(attrs)
        restriction = restriction.group(1) if restriction else None
        lk, rk = side_key(m.group(1)), side_key(m.group(2))
        if lk and restriction != "RL":
            glb_keys.add(lk)
        if rk and restriction != "LR":
            target_keys.add(rk)
    return glb_keys, target_keys


curated = {}       # lang -> (glb_keys, target_keys)
merge_target = {}  # lang -> dix path to merge into, or None
notes = defaultdict(list)

for lang, *_ in PAIRS:
    path = pair_dix_path(APERTIUM_ROOT, lang)
    merge_target[lang] = path if os.path.exists(path) else None
    if not os.path.exists(path):
        fallback = pair_dix_path(FALLBACK_ROOT, lang)
        if os.path.exists(fallback):
            notes[lang].append(f"(fallback: {path} missing, curated part read"
                               f" from the installed {fallback}; not merged)")
            path = fallback
        else:
            notes[lang].append(f"(fallback: no pair dix found, curated part"
                               f" unknown, nothing excluded; not merged)")
            curated[lang] = (set(), set())
            continue
    with open(path, encoding="utf-8") as f:
        text = f.read()
    marker = text.find(APERTIUM_MARKER)
    if marker == -1:
        notes[lang].append(f"(fallback: no marker in {path}, curated part"
                           f" unknown, nothing excluded)")
        curated[lang] = (set(), set())
    else:
        curated[lang] = curated_keys(text[:marker])


# ── Stage B: check targets with the target analyser ─────────────────────
_STREAM_SPECIAL_RE = re.compile(r"([\^$/<>\[\]{}\\@*])")
_UNIT_RE = re.compile(r"\^(.*?)\$")


def analyse(lang, lemmas):
    """{lemma: [(reading lemma, [tags]), ...]} from {lang}.automorf.bin,
    or None when no analyser is found."""
    path = analyser_path(APERTIUM_ROOT, lang)
    if not os.path.exists(path):
        fallback = analyser_path(FALLBACK_ROOT, lang)
        if not os.path.exists(fallback):
            return None
        notes[lang].append(f"(fallback: {path} missing, analysed with {fallback})")
        path = fallback
    lemmas = sorted(lemmas)
    text = "\n".join(_STREAM_SPECIAL_RE.sub(r"\\\1", l) for l in lemmas) + "\n"
    out = subprocess.run(["lt-proc", "-w", path], input=text,
                         capture_output=True, text=True, check=True).stdout
    lines = out.split("\n")
    result = {}
    for lemma, line in zip(lemmas, lines):
        units = _UNIT_RE.findall(line)
        readings = []
        if len(units) == 1:
            for rd in units[0].split("/")[1:]:
                if rd.startswith("*"):
                    continue
                tags = re.findall(r"<([^>]+)>", rd)
                rlemma = re.sub(r"<[^>]+>", "", rd)
                if not SKIP_READING_TAGS & set(tags):
                    readings.append((rlemma, tags))
        result[lemma] = readings if len(units) == 1 else "multiword"
    if len(lines) - 1 != len(lemmas):
        notes[lang].append(f"(fallback: analyser returned {len(lines) - 1} lines"
                           f" for {len(lemmas)} lemmas; unmatched ones dropped)")
    return result


def target_check(readings, target, sym, lang=None):
    """(lemma, genders, sint, reason); lemma None when the target is dropped.
    The lemma is the target itself, except for gendered noun forms the
    analyser files under another lemma (cuisinière → cuisinier<n><f>) and
    attributive adjective forms filed under the bare lemma (偉大な → 偉大).
    sym is the target-side symbol (TARGET_SYMBOLS)."""
    if readings == "multiword" or readings is None:
        return None, [], False, "multiword not in the analyser"
    if not readings:
        return None, [], False, "unknown to the analyser"
    same = [tags for rl, tags in readings if rl == target and tags and tags[0] == sym]
    if not same and sym == "adj" and target.endswith(ATTRIBUTIVE_ENDINGS.get(lang, ())):
        bare = target[:-1]
        if [tags for rl, tags in readings if rl == bare and tags and tags[0] == sym]:
            return bare, [], False, ""
    if same:
        genders = sorted({t for tags in same for t in tags if t in TARGET_GENDERS})
        sint = any("sint" in tags for tags in same)
        return target, genders, sint, ""
    if sym == "n":
        # Singular noun readings with a gender, all under one other lemma.
        forms = [(rl, tags) for rl, tags in readings
                 if tags and tags[0] == "n" and "sg" in tags
                 and TARGET_GENDERS & set(tags) and "#" not in rl]
        lemmas = {rl for rl, _ in forms}
        if len(lemmas) == 1 and len(forms) == len(readings):
            genders = sorted({t for _, tags in forms for t in tags if t in TARGET_GENDERS})
            return lemmas.pop(), genders, False, ""
    if any("#" in rl for rl, _ in readings):
        return None, [], False, "multiword with an inflecting head: needs a hand <g> entry"
    other_pos = sorted({tags[0] for rl, tags in readings if rl == target and tags})
    if other_pos:
        return None, [], False, f"analyser has it only as: {', '.join(other_pos)}"
    other_lemmas = sorted({rl for rl, _ in readings})
    if lang in REJOINED_COMPOUNDS and any("+" in rl and rl.replace("+", "") == target
                                         for rl in other_lemmas):
        return target, [], False, "compound"
    return None, [], False, f"analyser lemma differs: {', '.join(other_lemmas[:3])}"


# ── Stage C: decide directions, write entries, merge ────────────────────
entry_rows = []
summary = {}

for lang, label, *_ in PAIRS:
    cands = list(candidates[lang].values())
    analysis = analyse(lang, {c["target"] for c in cands})
    if analysis is None:
        notes[lang].append("no analyser found: pair skipped")
        summary[lang] = Counter()
        continue
    glb_curated, target_curated = curated[lang]
    stats = Counter()
    lines_both, lines_rl = [], []
    emitted = set()

    for c in cands:
        glb, sym, target, origin = c["glb"], c["sym"], c["target"], c["origin"]
        tsym = TARGET_SYMBOLS.get(lang, {}).get(sym, sym)
        lemma, genders, sint, reason = target_check(analysis.get(target), target, tsym, lang)
        fallback = ""
        if lemma is None and lang in PROPER_AS_COMMON and sym == "np":
            lemma, genders, sint, reason = target_check(analysis.get(target), target, "n", lang)
            if lemma is not None:
                tsym = "n"
                fallback = "(fallback: the target files this proper noun as a common noun <n>)"
        if reason == "compound":
            fallback = "; ".join(filter(None, [fallback,
                "compound the analyser splits (re-joined at run time by compounds.py)"]))
        if lemma is None:
            drop(lang, glb, sym, target, origin, reason)
            stats[f"dropped: {reason.split(':')[0]}"] += 1
            continue

        note = fallback
        if lemma != target:
            note = f"analyser files {target} under {lemma}"
            stats["form filed under another lemma"] += 1
            target, c = lemma, dict(c, wikt_genders=[])

        can_lr = origin == "wordlist" and (glb, sym) not in glb_curated
        can_rl = (target, tsym) not in target_curated
        if not can_lr and not can_rl:
            drop(lang, glb, sym, target, origin, "curated part covers it")
            stats["dropped: curated"] += 1
            continue
        restriction = None if can_lr and can_rl else ("LR" if can_lr else "RL")
        if origin == "wordlist" and restriction:
            note = "; ".join(filter(None, [
                note, f"{restriction} only: curated part covers the other direction"]))

        # Target gender: the analyser's, narrowed by Wiktionary's marker.
        if lang in NO_TARGET_GENDER:
            genders = []
        elif sym in NOUN_SYMBOLS and genders:
            narrowed = [g for g in c["wikt_genders"] if g in genders]
            if narrowed:
                genders = narrowed
            elif len(genders) > 1:
                note = "; ".join(filter(None, [note,
                    "(fallback: gender ambiguous in the analyser, no Wiktionary"
                    " gender to choose; all kept)"]))
        else:
            genders = []

        glb_gs = globasa_genders(glb) if sym in NOUN_SYMBOLS else [None]
        for gg in glb_gs:
            for tg in (genders or [None]):
                line = bilingual_entry(label, glb, GLB_SYMBOLS.get(sym, sym), gg,
                                       target, tsym, tg, restriction, sint=sint)
                if line in emitted:
                    continue
                emitted.add(line)
                (lines_both if origin == "wordlist" else lines_rl).append(line)
                entry_rows.append({"lang": lang, "glb": glb, "glb_pos": sym,
                                   "glb_gender": gg or "", "target": target,
                                   "target_pos": tsym, "target_gender": tg or "",
                                   "origin": origin, "dir": restriction or "both",
                                   "note": note})
                stats[f"{origin} {restriction or 'both'}"] += 1
        if "fallback" in note:
            stats["fallback: ambiguous gender"] += 1

    stats["dropped: function word (curated only)"] = sum(
        r["lang"] == lang and r["reason"].startswith("function word") for r in report)
    xml_path = f"dictionary_{lang}_bidix.xml"
    with open(xml_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines_both + lines_rl) + "\n")
    summary[lang] = stats
    if merge_target[lang] and lang not in MERGE_LANGS:
        notes[lang].append(f"not merged (BIDIX_MERGE={','.join(sorted(MERGE_LANGS))});"
                           f" {xml_path} written")
    elif merge_target[lang]:
        merge_into_dix(merge_target[lang], xml_path, require_marker=True)


with open(ENTRIES_TSV, "w", newline="", encoding="utf-8") as f:
    w = csv.DictWriter(f, fieldnames=list(entry_rows[0]) if entry_rows else ["lang"],
                       delimiter="\t", lineterminator="\n")
    w.writeheader()
    w.writerows(entry_rows)
with open(REPORT_TSV, "w", newline="", encoding="utf-8") as f:
    w = csv.DictWriter(f, fieldnames=["lang", "glb", "glb_pos", "target", "origin", "reason"],
                       delimiter="\t", lineterminator="\n")
    w.writeheader()
    w.writerows(report)

print()
for lang, *_ in PAIRS:
    print(f"glb-{lang}:")
    for note in notes[lang]:
        print(f"  {note}")
    for k, v in sorted(summary.get(lang, {}).items()):
        print(f"  {v:7d}  {k}")
print(f"\nWrote {ENTRIES_TSV} ({len(entry_rows)} entries), {REPORT_TSV}"
      f" ({len(report)} dropped), dictionary_{{lang}}_bidix.xml")
