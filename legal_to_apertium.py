"""Legal register for eng->glb (AP_SETVAR=legal), generated from legal_wordlist.tsv.

legal_wordlist.tsv is the source of truth (one row per item: item, english, how, glb,
default_glb, gold, note); this script only reads it and writes, in apertium-glb-eng:

  apertium-glb-eng.eng-glb.legal.rlx      biprefs CG fragment (concatenated by the Makefile)
  eng-glb.legal.preferences.xml           the preference declaration (translation aide switch)

The preference is a plain switch, orthogonal to eng_variety (GB/US/Victorian): no rule here
reads eng_variety and no variety rule reads legal.

how:
  jussive  a modal whose target tense the rtx turns into a particle: pres -> imp makes the
           rtx emit am instead of xa (rtx: tense > tense_shall). Not when the modal is the
           first verb after a relative hu ("a world in which human beings shall enjoy").
  recital  a capitalised clause opener that selects glb in legal mode; the default rule
           removes glb everywhere else (default_glb remains)."""
import csv

PAIR = "GlobasaTranslation/apertium-glb-eng/"
VERBS = "(vblex) OR (vbser) OR (vbmod) OR (vbhaver) OR (vbdo)"

rows = list(csv.DictReader(open("legal_wordlist.tsv", encoding="utf-8"), delimiter="\t"))
cg = ["# Legal register for eng->glb (AP_SETVAR=legal). Generated by legal_to_apertium.py from",
      "# legal_wordlist.tsv; do not edit. Orthogonal to eng_variety. Concatenated into",
      "# eng-glb.biprefs.rlx by the Makefile.", ""]
for r in rows:
    lemma = r["english"].split("<", 1)[0]
    cg.append(f"# {r['item']}: {r['note']}")
    if r["how"] == "jussive":
        cg.append(f'SUBSTITUTE:legal_{r["item"]} (pres) (imp) ("{lemma}"i vbmod pres) '
                  f'IF (0 ("<{lemma}>"i) + (VAR:legal)) '
                  f'(NEGATE -1* ("hu"i) BARRIER {VERBS}) ;')
    elif r["how"] == "recital":
        cg.append(f'SELECT:legal_{r["item"]} ("{r["glb"]}"i) IF (0 ("<{lemma}>") + (VAR:legal)) ;')
        cg.append(f'REMOVE:default_{r["item"]} ("{r["glb"]}"i) IF (0 ("<{lemma.lower()}>"i)) ;')
    else:
        raise SystemExit(f"{r['item']}: unknown how {r['how']!r}")
    cg.append("")
open(PAIR + "apertium-glb-eng.eng-glb.legal.rlx", "w", encoding="utf-8").write("\n".join(cg))

items = "; ".join(f"{r['english'].split('<', 1)[0]} -> {r['glb']}" for r in rows)
xml = f"""<preferences>
  <preference id="legal">
    <description lang="eng">Legal register (legislation, declarations)</description>
    <long-description lang="eng">
      Legal English: {items}. Independent of the English variety (GB/US/Victorian).
      Generated from legal_wordlist.tsv by legal_to_apertium.py.
    </long-description>
  </preference>
</preferences>
"""
open(PAIR + "eng-glb.legal.preferences.xml", "w", encoding="utf-8").write(xml)
print(f"{len(rows)} legal items -> {PAIR}apertium-glb-eng.eng-glb.legal.rlx, eng-glb.legal.preferences.xml")
