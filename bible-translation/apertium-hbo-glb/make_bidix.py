#!/usr/bin/env python3
"""Build the apertium-hbo-glb bilingual dictionary from the curated list.

    python3 make_bidix.py [curated/bidix.tsv] [-o apertium-hbo-glb.hbo-glb.dix]

The curated TSV is the source of truth (one default per Hebrew lemma + PoS;
later rows for the same key are kept as documentation only).  Globasa tags
are not typed by hand: each Globasa lemma is looked up in the installed
apertium-glb analyser, so nouns get their gender (<ut>, <nt>, <m>, <f>) as the
generator expects.  Lemmas the analyser does not know are reported; they are
accepted only when their basis says "derived" (regular Globasa derivation).
"""

import argparse
import csv
import os
import re
import subprocess
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
GLB_SHARE = os.environ.get("APERTIUM_GLB",
                           "/usr/local/old-apertium-2024/share/apertium/apertium-glb")
AUTOMORF = os.path.join(GLB_SHARE, "glb.automorf.bin")
GENDER_PREF = ["ut", "nt", "m", "f", "GD"]


def read_curated(path):
    rows = []
    with open(path, encoding="utf-8") as f:
        lines = [l for l in f if l.strip() and not l.startswith("#")]
    for r in csv.DictReader(lines, delimiter="\t"):
        r = {k: (v or "").strip() for k, v in r.items()}
        r["hbo"] = unicodedata.normalize("NFC", r["hbo"])   # stream: U+FB2A etc.
        rows.append(r)
    return rows


def analyse(lemmas):
    """{lemma: set of tag tuples} from the apertium-glb analyser."""
    out = {}
    text = "\n".join(lemmas) + "\n"
    res = subprocess.run(["lt-proc", "-w", AUTOMORF], input=text, capture_output=True,
                         text=True, check=True).stdout
    for unit in re.findall(r"\^([^$]*)\$", res):
        surf, *readings = unit.split("/")
        tags = set()
        for rd in readings:
            if "<cmp>" in rd or rd.startswith("*"):
                continue                  # compound-only-L parts, unknown words
            lem = rd.split("<")[0]
            if lem != surf:
                continue
            tags.add(tuple(t for t in re.findall(r"<([^>]+)>", rd)
                           if not t.startswith("compound")))
        out[surf] = tags
    return out


def glb_tags(lemma, pos, analyses):
    """Full Globasa tag list for lemma + PoS, or None if the analyser lacks it."""
    if pos == "prn":
        return ["prn"]
    cands = [t for t in analyses.get(lemma.lower(), ()) if t and t[0] == pos]
    if not cands:
        return None
    if pos == "n":
        for g in GENDER_PREF:
            for t in cands:
                if len(t) > 1 and t[1] == g:
                    return ["n", g]
        return ["n"]
    return [pos]


def xml(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("curated", nargs="?", default=os.path.join(HERE, "curated", "bidix.tsv"))
    ap.add_argument("-o", "--out", default=os.path.join(HERE, "apertium-hbo-glb.hbo-glb.dix"))
    a = ap.parse_args()
    rows = read_curated(a.curated)
    analyses = analyse(sorted({r["glb"].lower() for r in rows if r["glb_pos"] != "prn"}))
    seen, entries, problems, sdefs = set(), [], [], {"sent"}
    for r in rows:
        key = (r["hbo"], r["hbo_pos"])
        if key in seen:
            continue                      # alternatives: documentation only
        seen.add(key)
        tags = glb_tags(r["glb"], r["glb_pos"], analyses)
        if tags is None:
            if r["basis"].startswith("derived"):
                tags = ["n", "nt"] if r["glb_pos"] == "n" else [r["glb_pos"]]
            else:
                problems.append(f"{r['hbo']}<{r['hbo_pos']}> -> {r['glb']}<{r['glb_pos']}>: "
                                "not in apertium-glb (fix the list or mark basis 'derived')")
                continue
        sdefs.update(tags)
        sdefs.add(r["hbo_pos"])
        glb = r["glb"]                    # case is kept: Teo generates as "Teo"
        entries.append(
            f'    <e r="LR"><p><l>{xml(r["hbo"])}<s n="{r["hbo_pos"]}"/></l>'
            f'<r>{xml(glb)}{"".join(f"<s n={chr(34)}{t}{chr(34)}/>" for t in tags)}</r></p></e>'
            f'  <!-- {xml(r["basis"])} -->')
    if problems:
        print("\n".join(problems), file=sys.stderr)
        sys.exit(1)
    with open(a.out, "w", encoding="utf-8") as f:
        f.write('<?xml version="1.0" encoding="UTF-8"?>\n'
                '<!-- GENERATED by make_bidix.py from curated/bidix.tsv: edit the TSV, not this file -->\n'
                "<dictionary>\n  <alphabet/>\n  <sdefs>\n")
        for s in sorted(sdefs):
            f.write(f'    <sdef n="{s}"/>\n')
        f.write('  </sdefs>\n  <section id="main" type="standard">\n')
        f.write('    <e r="LR"><p><l>׃<s n="sent"/></l><r>.<s n="sent"/></r></p></e>\n')
        f.write("\n".join(entries) + "\n  </section>\n</dictionary>\n")
    print(f"{len(entries)} entries -> {a.out}")


if __name__ == "__main__":
    main()
