# Victorian word list -> Apertium preferences in the eng->glb pair
# (GlobasaTranslation/apertium-glb-eng). Output only: the source of truth is
# time-machine/victorian_wordlist.tsv; nothing is read back from the pair.
#
#   python3 time-machine/victorian_wordlist.py check   # first
#   python3 time-machine/termbase_to_apertium.py
#   (cd GlobasaTranslation/apertium-glb-eng && make)
#
# Mechanism (apertium >= 3.9 "preferences", as in apertium-nno-nob): the
# bidix carries both the modern and the period translation; a CG file run
# right after `lt-proc -b` (biprefs) keeps the modern one unless the stream
# variable is set. AP_SETVAR values:
#   (unset)                     modern defaults (presently -> nunli)
#   victorian                   every period sense (VAR:victorian=* = set
#                               without a value)
#   victorian=presently:queer   only the listed headwords
#   victorian=-queer            all but queer (the `apertium` script expands
#                               the negation from prefs/eng-glb.xml options)
#   eng_variety=Victorian       same as victorian: Victorian is offered as a
#                               variety of English (with GB and US), and the
#                               British-sense rules fire for it too
#
# From the rows with apertium=pref or apertium=add it writes:
#   apertium-glb-eng.glb-eng.dix   the block between BEGIN/END victorian
#                                  (replaced wholesale, placed above the
#                                  build_bidix marker); entries r="RL"
#                                  (eng->glb only), tags from the word list
#   apertium-glb-eng.eng-glb.victorian.rlx      SELECT/REMOVE per pref row
#   eng-glb.victorian.preferences.xml           preference "victorian", one
#                                               option per pref headword
# The pair's Makefile concatenates these with the English-variety fragments
# (eng_variety_to_apertium.py) into eng-glb.biprefs.rlx.bin and
# prefs/eng-glb.xml. Victorian English is British English: the British-sense
# rules live once, in the variety fragment, and fire for AP_SETVAR=victorian
# as well as for eng_variety=GB.
# An "add" row needs no rule: it is the only translation of its word.
import html
import re
import sys
from pathlib import Path

HERE = Path(__file__).parent
PAIR = HERE.parent / "GlobasaTranslation" / "apertium-glb-eng"
DIX = PAIR / "apertium-glb-eng.glb-eng.dix"
RLX = PAIR / "apertium-glb-eng.eng-glb.victorian.rlx"
PREFS = PAIR / "eng-glb.victorian.preferences.xml"
MARK = "<!-- Autogenerated common words -->"
BEGIN = "<!-- BEGIN victorian: generated from time-machine/victorian_wordlist.tsv by termbase_to_apertium.py; do not edit -->"
END = "<!-- END victorian -->"

lines = (HERE / "victorian_wordlist.tsv").read_text(encoding="utf-8").rstrip("\n").split("\n")
hdr = lines[0].split("\t")
rows = [dict(zip(hdr, ln.split("\t"))) for ln in lines[1:] if ln.strip()]
rows = [r for r in rows if r["apertium"] in ("pref", "add")]
bad = [r["headword"] for r in rows if " " in r["headword"] or " " in r["glb"].strip()
       or not r["eng_tags"] or r["eng_tags"] == "mwe" or not r["glb_tags"]]
if bad:
    sys.exit(f"rows not exportable (run victorian_wordlist.py check): {bad}")


def tags(dotted):
    return "".join(f'<s n="{t}"/>' for t in dotted.split("."))


entries, rules, options = [], [], set()
for r in sorted(rows, key=lambda r: (r["headword"], r["glb"])):
    h, g = r["headword"].lower(), r["glb"].strip()
    note = html.escape(f"{r['apertium']}: {r['sense']}"[:70]).replace("--", "-")
    entries.append(f'<e r="RL"><p><l>{html.escape(g)}{tags(r["glb_tags"])}</l>   '
                   f'<r>{html.escape(h)}{tags(r["eng_tags"])}</r></p></e>  <!-- {note} -->')
    if r["apertium"] == "pref":
        pos = r["glb_tags"].split(".")[0]
        target, src = f'("{g}"i {pos})', f'("<{h}>"i)'
        rules.append(f"# {h} <{r['eng_tags']}>: {r['sense'][:70]}\n"
                     f"SELECT:vic_only {target} IF (0 {src} + (VAR:victorian=/.*{re.escape(h)}.*/r)) ;\n"
                     f"SELECT:vic_all {target} IF (0 {src} + (VAR:victorian=*)) ;\n"
                     f"SELECT:vic_variety {target} IF (0 {src} + (VAR:eng_variety=Victorian)) ;\n"
                     f"REMOVE:modern_default {target} IF (0 {src}) ;\n")
        options.add(h)

dix = DIX.read_text(encoding="utf-8")
dix = re.sub(re.escape("<!-- BEGIN victorian") + r".*?" + re.escape(END) + r"\n?", "", dix, flags=re.S)
i = dix.find(MARK)
if i < 0:
    sys.exit(f"no '{MARK}' in {DIX}")
DIX.write_text(dix[:i] + BEGIN + "\n" + "\n".join(entries) + "\n" + END + "\n" + dix[i:], encoding="utf-8")

RLX.write_text(
    "# Victorian English period senses: bidix preferences for eng->glb.\n"
    "# Generated from time-machine/victorian_wordlist.tsv by termbase_to_apertium.py; do not edit.\n"
    "# Default = modern translation; AP_SETVAR=victorian selects all period senses,\n"
    "# victorian=presently:queer only those headwords.\n\n"
    'DELIMITERS = "." ;\n\n' + "\n".join(rules), encoding="utf-8")

opts = "\n".join(f'      <option id="{o}"/>' for o in sorted(options))
PREFS.write_text(f"""<preferences>
  <!-- Generated from time-machine/victorian_wordlist.tsv by termbase_to_apertium.py; do not edit. -->
  <preference id="victorian">
    <description lang="eng">Victorian English: period senses (presently → soon, queer → strange, …)</description>
    <long-description lang="eng">
      Translate words in the sense they had in Victorian English (about 1840–1900) rather than
      their modern sense: "presently" = soon, "queer" = strange, "curious" = strange.
      Set without a value for all of them, or list headwords to choose only some.
      Implies British English input (the eng_variety=GB senses: fall = falling, not autumn).
    </long-description>
    <options>
{opts}
    </options>
  </preference>
</preferences>
""", encoding="utf-8")
print(f"{len(entries)} bidix entries ({len(rules)} preferences, {len(entries) - len(rules)} additions)")
